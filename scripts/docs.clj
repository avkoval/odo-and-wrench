;; bb docs — generated documentation, so it always reflects the model and the code:
;;   docs/slices.md            every slice of model/event-model.yaml with its implementation status
;;   model/event-model.svg/png the diagram rendered from model/event-model.d2
(require '[clj-yaml.core :as yaml]
         '[clojure.string :as str]
         '[babashka.process :refer [shell]])

(def model (yaml/parse-string (slurp "model/event-model.yaml")))

(def implemented
  "Slice ids registered in the code (src/auto_maintenance/slices.cljd)."
  (set (map second (re-seq #"(?m)^\s+[{]?\"([a-z0-9-]+)\" \{:(?:decide|project)" (slurp "src/auto_maintenance/slices.cljd")))))

(defn cell [x] (str/replace (str x) "|" "\\|"))

(defn row [{:keys [id type screen command read_model events gwt gt]}]
  (str "| " (if (implemented id) "✓" "–") " | `" id "` | " type " | " (or screen "") " | "
       (cell (or (some-> command (str " (command)")) (some-> read_model (str " (read model)")) "")) " | "
       (str/join ", " (map #(str "`" % "`") events)) " | " (count (concat gwt gt)) " |"))

(let [slices (:slices model)
      done (count (filter (comp implemented :id) slices))
      out (str "# Slices of the event model\n\n"
               "Generated by `bb docs` from [model/event-model.yaml](../model/event-model.yaml) and the slice registry in\n"
               "[src/auto_maintenance/slices.cljd](../src/auto_maintenance/slices.cljd) — do not edit by hand.\n\n"
               "**" done " of " (count slices) " slices implemented** (✓ = registered in the code and its scenarios pass in\n"
               "`bb test`). Diagram: [model/event-model.svg](../model/event-model.svg).\n\n"
               "| | Slice | Type | Screen | Command / read model | Events | Scenarios |\n"
               "|---|---|---|---|---|---|---|\n"
               (str/join "\n" (map row slices))
               "\n\n## Glossary\n\n"
               (str/join "\n" (for [[term text] (:glossary model)] (str "- **" (name term) "** — " text)))
               "\n")]
  (spit "docs/slices.md" out)
  (println (str "docs/slices.md: " done "/" (count slices) " slices implemented")))

(shell {:dir "model"} "d2 --theme 0 event-model.d2 event-model.svg")
(shell {:dir "model"} "d2 --theme 0 event-model.d2 event-model.png")
